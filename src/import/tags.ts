/**
 * Stage 1 — tags, as materialised paths, normalised on the way in.
 *
 * SPEC, "Hierarchical tags": store the full path string and index every prefix,
 * and the sidebar tree plus arbitrary nesting depth fall out with no schema
 * change. `Dialect/Kansai` is already in the corpus, so the path type is not
 * speculative.
 *
 * WHY NORMALISATION IS NOT OPTIONAL (measured, see test/tags-links.test.ts)
 *
 *   Five raw tags carry a leading U+200B ZERO WIDTH SPACE. It is invisible in
 *   any UI, so the tag list reads as duplicates that cannot be told apart:
 *
 *     Mathematics  8 cards  vs  <ZWSP>Mathematics  1 card
 *     Computing    2        vs  <ZWSP>Computing    1
 *     Finance      1        vs  <ZWSP>Finance      1
 *     Logic        1        vs  <ZWSP>Logic        1
 *     <ZWSP>Buddhism  8 cards / 11 occurrences — no clean counterpart at all
 *
 *   NFKC, then strip every format character (\p{Cf}, which is where U+200B
 *   lives), then trim each segment: 23 raw tag strings collapse to 19 real
 *   ones. Four pairs merge and ␣Buddhism simply becomes Buddhism.
 *
 * WHAT THE EXPORT ACTUALLY HOLDS
 *
 *   * `tags` (66 occurrences, 23 distinct strings, 62 cards) and `manual-tags`
 *     (3 occurrences, 1 distinct string, 3 cards). `manual-tags` is a subset:
 *     all three of those cards carry the identical value in both arrays, so
 *     `manual` is an OR, not a separate row — `card_tags` is keyed
 *     (card_id, tag_path) and cannot hold both.
 *   * 20 tag ROWS for 19 tags that carry cards. `tags.parent_path` is a
 *     foreign key onto `tags.path`, so `Dialect/Kansai` cannot exist until
 *     `Dialect` does; the missing ancestor is synthesised here and reported in
 *     `notes.ancestorsSynthesised`. It has cards_direct = 0 in `tag_usage`.
 *     Any count that means "tags the user actually uses" must therefore filter
 *     on cards, not count rows.
 */

import type { Db } from "../db/index.js";

// ─── row shapes ──────────────────────────────────────────────────────────────

/** Columns of `tags`. `depth` is generated by SQLite, so it is not here. */
export interface TagRow {
  readonly path: string;
  readonly parent_path: string | null;
  /** Last segment. The schema CHECKs that it contains no slash. */
  readonly name: string;
}

/** Columns of `card_tags`. */
export interface CardTagRow {
  readonly card_id: string;
  readonly tag_path: string;
  readonly manual: 0 | 1;
}

/** A card, as far as tagging is concerned. */
export interface MochiTaggedCard {
  readonly id: string;
  /** Mochi's full tag set, `{"~#set": [...]}` decoded to an array. */
  readonly tags?: readonly unknown[] | null;
  /** The user-set subset. Never disjoint from `tags` in this corpus. */
  readonly "manual-tags"?: readonly unknown[] | null;
}

/** Two raw strings that normalised to the same path — the invisible duplicates. */
export interface TagMerge {
  readonly path: string;
  /** Every distinct raw spelling, in first-seen order. */
  readonly variants: readonly string[];
}

/** Everything the mapping noticed and the importer should log rather than bury. */
export interface TagNotes {
  /** Distinct raw strings across `tags` + `manual-tags`. 23 in the corpus. */
  readonly rawTags: number;
  /** Distinct paths after normalisation that carry at least one card. 19. */
  readonly normalisedTags: number;
  /** Paths whose raw spellings differed only by invisible characters. */
  readonly merged: readonly TagMerge[];
  /** Raw strings that normalise to nothing (all-format-character tags). */
  readonly dropped: readonly string[];
  /** Ancestor paths added to satisfy the foreign key. `Dialect` in the corpus. */
  readonly ancestorsSynthesised: readonly string[];
  /** (card, tag) pairs lost to normalisation because the card held both forms. */
  readonly duplicatePairsMerged: number;
}

export interface MappedTags {
  /** Parents before children, so `parent_path` inserts in one pass. */
  readonly tags: readonly TagRow[];
  readonly cardTags: readonly CardTagRow[];
  /**
   * Every card id this mapping SAW, tagged or not, collected on the same pass.
   *
   * `importTags` needs it to scope its prune, and it must come from here rather
   * than from a second walk of the caller's iterable: the parameter is typed
   * `Iterable`, so a generator would be exhausted by then and the delete would
   * silently match nothing — a prune that quietly does nothing is worse than no
   * prune, because it looks done.
   *
   * It cannot be derived from `cardTags` either. A card whose LAST tag was
   * removed in Mochi carries no `tags` array at all, so it is absent from that
   * list — and it is exactly the card the prune exists for.
   */
  readonly cardIds: readonly string[];
  readonly notes: TagNotes;
}

// ─── normalisation ───────────────────────────────────────────────────────────

/**
 * Every Unicode format character, which is the category U+200B–U+200D, U+FEFF
 * and U+00AD all belong to. Stripping the category rather than a hand-list is
 * what makes a future soft hyphen or bidi mark a non-event.
 */
const FORMAT_CHARS = /\p{Cf}/gu;

/**
 * NFKC, strip format characters, trim every segment, drop empty segments.
 *
 * Returns "" for a tag that is nothing but invisible characters — the caller
 * drops it rather than writing a tag with an empty name, which the schema's
 * `CHECK (name <> '')` would reject anyway.
 */
export function normaliseTagPath(raw: string): string {
  return raw
    .normalize("NFKC")
    .replace(FORMAT_CHARS, "")
    .split("/")
    .map((segment) => segment.trim())
    .filter((segment) => segment !== "")
    .join("/");
}

/** `a/b/c` -> ["a", "b", "c"]. Assumes an already-normalised path. */
export function tagSegments(path: string): string[] {
  return path === "" ? [] : path.split("/");
}

/** Every prefix of a path, shortest first, including the path itself. */
export function tagPrefixes(path: string): string[] {
  const segments = tagSegments(path);
  return segments.map((_segment, index) => segments.slice(0, index + 1).join("/"));
}

/** The row for one path: parent is the path minus its last segment. */
export function tagRow(path: string): TagRow {
  const segments = tagSegments(path);
  const name = segments[segments.length - 1] ?? "";
  return {
    path,
    parent_path: segments.length > 1 ? segments.slice(0, -1).join("/") : null,
    name,
  };
}

// ─── mapping ─────────────────────────────────────────────────────────────────

/**
 * Map every card's tags into `tags` + `card_tags` rows.
 *
 * Pure: no database, so the corpus can be checked without one. The returned
 * `tags` are ordered shallowest-first, which is the order the foreign key on
 * `parent_path` accepts.
 */
export function mapCardTags(cards: Iterable<MochiTaggedCard>): MappedTags {
  const variants = new Map<string, string[]>();
  const dropped: string[] = [];
  const rawTags = new Set<string>();
  /** card -> path -> manual. The map is what merges the invisible duplicates. */
  const perCard = new Map<string, Map<string, 0 | 1>>();
  let rawPairs = 0;

  const cardIds: string[] = [];

  for (const card of cards) {
    if (!card.id) continue;
    cardIds.push(card.id);
    for (const [manual, list] of [
      [0, card.tags],
      [1, card["manual-tags"]],
    ] as const) {
      for (const entry of list ?? []) {
        if (typeof entry !== "string") continue;
        rawTags.add(entry);
        const path = normaliseTagPath(entry);
        if (path === "") {
          if (!dropped.includes(entry)) dropped.push(entry);
          continue;
        }
        const seen = variants.get(path) ?? [];
        if (!seen.includes(entry)) seen.push(entry);
        variants.set(path, seen);

        rawPairs += 1;
        const onCard = perCard.get(card.id) ?? new Map<string, 0 | 1>();
        // manual is an OR: card_tags has one row per (card, path).
        onCard.set(path, (onCard.get(path) === 1 || manual === 1 ? 1 : 0) as 0 | 1);
        perCard.set(card.id, onCard);
      }
    }
  }

  const cardTags: CardTagRow[] = [];
  for (const [cardId, paths] of perCard) {
    for (const [path, manual] of paths) {
      cardTags.push({ card_id: cardId, tag_path: path, manual });
    }
  }

  // Every prefix must exist, because parent_path is a foreign key.
  const used = new Set(variants.keys());
  const paths = new Set<string>();
  const ancestorsSynthesised: string[] = [];
  for (const path of used) {
    for (const prefix of tagPrefixes(path)) {
      if (paths.has(prefix)) continue;
      paths.add(prefix);
      if (!used.has(prefix)) ancestorsSynthesised.push(prefix);
    }
  }

  return {
    tags: orderTags([...paths].map(tagRow)),
    cardTags,
    cardIds,
    notes: {
      rawTags: rawTags.size,
      normalisedTags: used.size,
      merged: [...variants]
        .filter(([, spellings]) => spellings.length > 1)
        .map(([path, spellings]) => ({ path, variants: spellings })),
      dropped,
      ancestorsSynthesised,
      duplicatePairsMerged: rawPairs - cardTags.length,
    },
  };
}

/**
 * Shallowest first, then alphabetical. `tags.parent_path` references
 * `tags.path`, so a child inserted before its parent fails the foreign key.
 */
export function orderTags(rows: readonly TagRow[]): TagRow[] {
  return [...rows].sort((a, b) => {
    const depth = tagSegments(a.path).length - tagSegments(b.path).length;
    return depth !== 0 ? depth : a.path < b.path ? -1 : a.path > b.path ? 1 : 0;
  });
}

// ─── writing ─────────────────────────────────────────────────────────────────

const INSERT_TAG = `
INSERT INTO tags (path, parent_path, name) VALUES (?, ?, ?)
ON CONFLICT (path) DO NOTHING`;

const INSERT_CARD_TAG = `
INSERT INTO card_tags (card_id, tag_path, manual) VALUES (?, ?, ?)
ON CONFLICT (card_id, tag_path) DO UPDATE SET manual = max(manual, excluded.manual)`;

/**
 * A TAG REMOVED IN MOCHI MUST BE REMOVED HERE. It was permanent until 2026-08-22.
 *
 * This module had no `DELETE` at all, while both of its siblings prune with a
 * written rationale — `pruneFieldValues` (src/import/index.ts) and
 * `DELETE_CARD_LINKS` (src/import/links.ts). The asymmetry was undocumented and
 * untested, and it matters because re-importing is not a one-off: Zach reviews
 * and tags in Mochi daily, so every fresh export was strictly ADDITIVE. Untag a
 * card there and the tag stayed here forever, indexed in `card_fts.tags` and
 * feeding the tag sidebar.
 *
 * The `manual` column had the same shape: `max(manual, excluded.manual)` is
 * monotonic, so a card promoted to a manual tag once could never go back.
 * Deleting the card's rows first makes both fall correctly.
 *
 * SCOPED TO THE CARDS IN THIS IMPORT, exactly as `pruneFieldValues` is. A card
 * that came from an export not being re-read must keep its tags — otherwise
 * importing one of the three exports would strip the other two.
 *
 * NOT A TOMBSTONE, and it does not need to be: `tags` rows are left alone even
 * when they lose their last card. That keeps `parent_path`'s foreign key intact
 * (the synthesised `Dialect` ancestor has no cards of its own and must survive),
 * and it is why every count of "tags he actually uses" filters `cards_direct > 0`
 * rather than counting rows.
 */
const DELETE_CARD_TAGS = "DELETE FROM card_tags WHERE card_id = ?";

export interface ImportTagsResult extends TagNotes {
  /** Rows written to `tags`, synthesised ancestors included. 20 in the corpus. */
  readonly tags: number;
  /** Rows written to `card_tags`. */
  readonly cardTags: number;
  /**
   * `card_tags` rows deleted first, i.e. what a re-import replaced. 0 on a fresh
   * database, and on a re-import it equals `cardTags` when nothing changed in
   * Mochi. Reported rather than inferred: the difference between this and
   * `cardTags` is exactly the tags he removed there, and that is the number
   * worth seeing.
   */
  readonly cardTagsReplaced: number;
}

/**
 * Write tags and card-tag links. Cards must already be in the database:
 * `card_tags.card_id` is a foreign key, and a card_tags insert also reindexes
 * that card in `card_fts` so tag paths are searchable.
 *
 * Idempotent — re-importing the same export writes nothing new — and wrapped in
 * one transaction, so a half-built tag tree is not a state this can produce.
 */
export function importTags(db: Db, cards: Iterable<MochiTaggedCard>): ImportTagsResult {
  const mapped = mapCardTags(cards);
  const insertTag = db.prepare(INSERT_TAG);
  const insertCardTag = db.prepare(INSERT_CARD_TAG);
  const deleteCardTags = db.prepare(DELETE_CARD_TAGS);

  // EVERY card in this import, not only the tagged ones — see MappedTags.cardIds
  // for why this comes from the mapping rather than from a second walk of the
  // caller's iterable.
  const cardIds = new Set(mapped.cardIds);

  let cardTagsReplaced = 0;
  db.transaction(() => {
    for (const id of cardIds) cardTagsReplaced += deleteCardTags.run(id).changes;
    for (const tag of mapped.tags) insertTag.run(tag.path, tag.parent_path, tag.name);
    for (const link of mapped.cardTags) {
      insertCardTag.run(link.card_id, link.tag_path, link.manual);
    }
  })();

  return {
    ...mapped.notes,
    tags: mapped.tags.length,
    cardTags: mapped.cardTags.length,
    cardTagsReplaced,
  };
}
